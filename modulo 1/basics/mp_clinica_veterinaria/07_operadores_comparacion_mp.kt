fun main() {

    println("Operadores de comparacion")
    var pesoPerro = 10
    var pesoGato = 2
    
    println("$pesoPerro == $pesoGato : ${pesoPerro==pesoGato}")
    println("$pesoPerro != $pesoGato : ${pesoPerro!=pesoGato}")
    println("$pesoPerro > $pesoGato : ${pesoPerro>pesoGato}")
    println("$pesoPerro < $pesoGato : ${pesoPerro<pesoGato}")
    println("$pesoPerro >= $pesoGato : ${pesoPerro>=pesoGato}")
    println("$pesoPerro <= $pesoGato : ${pesoPerro<=pesoGato}")
    
}