fun main() {

    //Operadores
    println("Operadores de comparacion")
    var num1 = 10
    var num2 = 2
    
    println("$num1 == $num2 : ${num1==num2}")
    println("$num1 != $num2 : ${num1!=num2}")
    println("$num1 > $num2 : ${num1>num2}")
    println("$num1 < $num2 : ${num1<num2}")
    println("$num1 >= $num2 : ${num1>=num2}")
    println("$num1 <= $num2 : ${num1<=num2}")
    
}